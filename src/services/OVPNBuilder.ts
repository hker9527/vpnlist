import { type Site, type Variant } from "../const";
import { generateDateTimeString } from "../utils";

const OVPN_TEMPLATE = `# Generated by Nasu VPN Checker (https://umavpn.top) at %TIME%

dev tun
proto %PROTO%
remote %IP% %PORT%
cipher AES-128-CBC
data-ciphers AES-128-CBC
auth SHA1
resolv-retry infinite
nobind
persist-key
persist-tun
client
verb 3

<ca>
%CA%
</ca>

<cert>
%CERT%
</cert>

<key>
%KEY%
</key>
`;

const SPLIT_SITES: Record<Site, { domains: readonly string[]; routeOnly?: readonly string[] }> = {
    uma: {
        domains: [
            "api-umamusume.cygames.jp",
            "api.games.umamusume.jp",
            "prd-storage-app-umamusume.akamaized.net",
            "prd-storage-game-umamusume.akamaized.net",
            "prd-info-umamusume.akamaized.net"
        ]
    },
    umag: {
        domains: [
            "api.games.umamusume.com",
            "assets-umamusume-en.akamaized.net"
        ]
    },
    dmm: {
        domains: ["apidgp-gameplayer.games.dmm.com"],
        routeOnly: ["tv.dmm.com"]
    }
};

function splitPatch(variant: Variant, sites?: readonly Site[]) {
    const selected = sites === undefined
        ? Object.values(SPLIT_SITES)
        : [...new Set(sites)].map(site => SPLIT_SITES[site]);
    const sections = [
        "# Route patch\nroute-nopull",
        ...selected.map(({ domains, routeOnly = [] }) =>
            [...domains, ...routeOnly].map(domain => `route ${domain}`).join("\n")),
        "# Split-tunnel diagnostic\nroute www.gco.gov.qa"
    ];

    if (variant === "beta" && selected.length > 0) {
        const dns = selected.map(({ domains }) =>
            domains.map(domain => `dns search-domains ${domain}`).join("\n")).join("\n\n");
        sections.unshift(`# DNS patch (Beta)\n${dns}`);
    }

    return `\n\n${sections.join("\n\n")}\n`.replaceAll("\n", "\r\n");
}

// Route global IPv6 into the TUN so block-ipv6 can reject it without changing IPv4 routes.
const BLOCK_IPV6_PATCH = `

# Block public IPv6 while connected
ifconfig-ipv6 fd15:53b6:dead::2/64 fd15:53b6:dead::1
route-ipv6 2000::/3
block-ipv6
`.replaceAll("\n", "\r\n");

export class OVPNBuilder {
    #time!: string;
    #proto!: string;
    #ip!: string;
    #port!: number;
    #ca!: string;
    #cert!: string;
    #key!: string;

    #getVariantShortCode(variant: Variant) {
        return {
            legacy: "L",
            current: "C",
            beta: "B"
        }[variant];
    }

    #getTypeShortCode(split?: boolean) {
        return typeof split !== "undefined" ? "S" : "O";
    }
    
    public setTime(time: string) {
        this.#time = time;
        return this;
    }

    public setProto(proto: string) {
        this.#proto = proto;
        return this;
    }

    public setIp(ip: string) {
        this.#ip = ip;
        return this;
    }

    public setPort(port: number) {
        this.#port = port;
        return this;
    }

    public setCa(ca: string) {
        this.#ca = ca;
        return this;
    }

    public setCert(cert: string) {
        this.#cert = cert;
        return this;
    }

    public setKey(key: string) {
        this.#key = key;
        return this;
    }

    public build({ variant, split, blockIpv6 = true, sites }: {
        variant: Variant;
        split?: boolean;
        blockIpv6?: boolean;
        sites?: readonly Site[];
    }) {
        let config = OVPN_TEMPLATE
            .replace("%TIME%", this.#time)
            .replace("%PROTO%", this.#proto)
            .replace("%IP%", this.#ip)
            .replace("%PORT%", this.#port.toString())
            .replace("%CA%", this.#ca)
            .replace("%CERT%", this.#cert)
            .replace("%KEY%", this.#key);

        if (variant === "legacy") {
            // Remove line starts with "data-ciphers"
            config = config.replace(/^data-ciphers.+\n/m, "");
        }

        if (typeof split !== "undefined") {
            config += splitPatch(variant, sites);
        }

        if (blockIpv6) {
            config += BLOCK_IPV6_PATCH;
        }

        return {
            filename: `NasuVPN-${generateDateTimeString()}-${this.#ip}-${this.#getVariantShortCode(variant)}${this.#getTypeShortCode(split)}.ovpn`,
            content: config
        };
    }
}
